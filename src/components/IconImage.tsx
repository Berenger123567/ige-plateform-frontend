import type { CSSProperties } from 'react';

type IconImageProps = {
  className?: string;
  size?: number | string;
  color?: string;
  style?: CSSProperties;
};

const createIcon = (name: string) =>
  function IconImage({ className = '', size, color, style }: IconImageProps) {
    return (
      <span
        aria-hidden="true"
        className={`ige-icon-image ${className}`}
        style={{
          maskImage: `url("/icons/${name}.svg")`,
          WebkitMaskImage: `url("/icons/${name}.svg")`,
          ...(size !== undefined ? { width: size, height: size } : {}),
          ...(color ? { color } : {}),
          ...style,
        }}
      />
    );
  };

